CREATE TABLE IF NOT EXISTS tk_overdue_ar_remark (
  cust_code VARCHAR(64) NOT NULL COMMENT '金蝶客户编码',
  currency_code VARCHAR(32) NOT NULL DEFAULT '' COMMENT '金蝶币种编码（如 PRE001）',
  remark VARCHAR(500) NOT NULL COMMENT '逾期备注',
  updated_by VARCHAR(64) NOT NULL DEFAULT '' COMMENT '最后修改人',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (cust_code, currency_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='客户逾期应收备注';
