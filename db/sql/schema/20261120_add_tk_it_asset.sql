-- IT电脑资产台账表
CREATE TABLE IF NOT EXISTS tk_it_asset (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  asset_no VARCHAR(64) NOT NULL COMMENT '资产编号（唯一，如 TK-PC-0001）',
  asset_name VARCHAR(120) NOT NULL COMMENT '资产名称',
  device_type VARCHAR(32) NOT NULL DEFAULT 'desktop' COMMENT '设备类型：desktop/laptop/all_in_one/workstation/monitor/server/other',
  brand VARCHAR(64) DEFAULT NULL COMMENT '品牌',
  model VARCHAR(120) DEFAULT NULL COMMENT '规格型号',
  serial_no VARCHAR(100) DEFAULT NULL COMMENT '出厂序列号 SN',
  use_dept VARCHAR(100) DEFAULT NULL COMMENT '使用部门',
  user_userid VARCHAR(64) DEFAULT NULL COMMENT '使用人企微UserID',
  user_name VARCHAR(64) DEFAULT NULL COMMENT '使用人姓名',
  location VARCHAR(120) DEFAULT NULL COMMENT '存放地点',
  purchase_date DATE DEFAULT NULL COMMENT '购置日期',
  status VARCHAR(32) NOT NULL DEFAULT 'in_use' COMMENT '资产状态：in_use/idle/repair/scrapped',
  cpu_spec VARCHAR(100) DEFAULT NULL COMMENT 'CPU配置',
  memory_spec VARCHAR(64) DEFAULT NULL COMMENT '内存配置',
  disk_spec VARCHAR(64) DEFAULT NULL COMMENT '硬盘配置',
  os_version VARCHAR(80) DEFAULT NULL COMMENT '操作系统',
  ip_address VARCHAR(64) DEFAULT NULL COMMENT 'IP地址',
  mac_address VARCHAR(64) DEFAULT NULL COMMENT 'MAC地址',
  warranty_date DATE DEFAULT NULL COMMENT '保修到期日',
  print_count INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '标签打印次数',
  last_printed_at DATETIME DEFAULT NULL COMMENT '最近打印时间',
  remark VARCHAR(500) DEFAULT NULL COMMENT '备注',
  created_by_id BIGINT DEFAULT NULL COMMENT '创建人ID',
  created_by_name VARCHAR(64) DEFAULT NULL COMMENT '创建人姓名',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_by_id BIGINT DEFAULT NULL COMMENT '更新人ID',
  updated_by_name VARCHAR(64) DEFAULT NULL COMMENT '更新人姓名',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_tk_it_asset_no (asset_no),
  KEY idx_tk_it_asset_status (status),
  KEY idx_tk_it_asset_dept (use_dept),
  KEY idx_tk_it_asset_user (user_name),
  KEY idx_tk_it_asset_type (device_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='IT电脑资产台账';
